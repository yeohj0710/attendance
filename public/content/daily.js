const hash = (s) => { let h = 0; for (const c of s) h = (h * 31 + c.charCodeAt(0)) | 0; return (h >>> 0).toString(36); };
const plain = (s) => String(s || "").replace(/<[^>]+>/g, "");
const keyOf = (who, d, it) => `${who}:${d}:${hash(it.k + plain(it.t))}`;
const API = "/api/calendar";
