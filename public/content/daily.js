function openEditor(who, it) {
  let dlg = document.getElementById("editor");
  if (!dlg) { dlg = el("dialog", "editor"); dlg.id = "editor"; document.body.appendChild(dlg); }
  const cur = it.own ? (parse(SH.add[it.id]) || {}).d : SH.move[it.key] || it.orig;
  const opts = ALL_DAYS.filter((d) => !before(d, "10-07")).map((d) => `<option value="${d}" ${d === cur ? "selected" : ""}>${lab(d)} (${DOW[dow(d)]})${HOLIDAYS[d] ? " " + HOLIDAYS[d] : ""}</option>`).join("");
  dlg.innerHTML = `<form method="dialog"><h3>${it.own ? "추가한 할 일" : "할 일 고치기"}</h3>` +
    `<label>할 일<input name="t" value="${esc(plain(it.t))}" required maxlength="200"/></label>` +
    `<label>메모<textarea name="sub" rows="3" maxlength="600">${esc(plain(it.sub))}</textarea></label>` +
    `<label>날짜<select name="d">${opts}</select></label>` +
    `<div class="ed-btns"><button type="button" class="ed-del">지우기</button><span></span><button value="cancel" type="button" class="ed-cancel">취소</button><button value="ok" class="ed-ok">저장</button></div></form>`;
  const f = dlg.querySelector("form");
  dlg.querySelector(".ed-cancel").onclick = () => dlg.close();
  dlg.querySelector(".ed-del").onclick = () => { dlg.close(); deleteItem(who, it); };
  f.onsubmit = (e) => {
    e.preventDefault();
    const t = f.t.value.trim(), sub = f.sub.value.trim(), d = f.d.value;
    if (!t) return;
    if (it.own) {
      push("set", "add", it.id, { who, d, t, sub });
    } else {
      const changed = {};
      if (t !== plain(it.t).trim()) changed.t = t;
      if (sub !== plain(it.sub).trim()) changed.sub = sub;
      const prev = parse(SH.edit[it.key]) || {};
      const next = Object.assign(prev, changed);
      if (Object.keys(changed).length) push("set", "edit", it.key, next);
      if (d !== cur) { if (d === it.orig) push("del", "move", it.key); else push("set", "move", it.key, d); }
    }
    dlg.close();
    renderPerson(who);
    toast("저장했어요");
  };
  dlg.showModal();
  f.t.focus();
}

