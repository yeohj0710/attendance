function nextWorkDay(k) {
  let next = add(TODAY, 1);
  for (let i = 0; i < 14 && !workDayFor(k, next); i++) next = add(next, 1);
  return next;
}
/* 출퇴근기록부에서 마우스를 올리면 뜨는 설명 한 덩어리. 설명, 하는 순서, 참고, 걸리는 시간 순 */
function noteText(d) {
  const parts = [];
  if (d.tag) parts.push(`지금 상태: ${d.tag}`);
  if (d.sub) parts.push(d.sub);
  if (d.steps.length) parts.push("하는 순서\n" + d.steps.map((x, i) => `${i + 1}. ${x}`).join("\n"));
  if (d.ref) parts.push(d.ref);
  if (d.links.length) parts.push(d.links.map((a) => `${a.t}: ${a.href}`).join("\n"));
  if (d.moved) parts.push(`${d.moved}에서 옮겨 온 일이에요.`);
  if (d.min) parts.push(d.min.startsWith("AI ") ? `AI에 맡기면 ${d.min.slice(3)} 정도 걸려요.` : `${d.min} 정도 걸려요.`);
  return parts.join("\n\n");
}
function itemData(k, it) {
  const e = est(it);
  const box = document.createElement("div");
  box.innerHTML = (it.sub ? `<p>${it.sub.replace(/<br\s*\/?>/g, "\n")}</p>` : "") + howHtml(k, it);
  const links = [...box.querySelectorAll("a"), ...new DOMParser().parseFromString(it.t, "text/html").querySelectorAll("a")]
    .map((a) => ({ t: a.textContent.trim(), href: a.href })).filter((a) => /^https?:/.test(a.href));
  return {
    key: it.key, kind: it.lb && it.k !== "own" ? plain(it.lb) : KIND[it.k], k: it.k,
    title: plain((it.time ? it.time + " " : "") + polite(it.t)), tag: it.tag ? it.tag[0] : "",
    min: e ? (e.ai ? "AI " : "") + (e.txt || fmtMin(e.m)) : "", m: e ? e.m : 0,
    sub: it.sub ? plain(it.sub.replace(/<br\s*\/?>/g, "\n")).trim() : "", steps: [...box.querySelectorAll(".how li")].map((x) => x.textContent.trim()),
    ref: box.querySelector(".ref") ? box.querySelector(".ref").textContent.trim() : "",
    moved: it.moved ? lab(it.moved) : "", links, done: !!SH.done[it.key],
  };
}
function itemOut(k, it) {
  const d = itemData(k, it);
  d.note = noteText(d);
  return d;
}
function dayData(k, byDay, d) {
  const list = (byDay[d] || []).map((it) => itemOut(k, it));
  list.sort((a, b) => (a.done ? 1 : 0) - (b.done ? 1 : 0));
  return { d, label: `${lab(d)} ${DOW[dow(d)]}`, work: workDayFor(k, d), items: list };
}
