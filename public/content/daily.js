async function pull() {
  try {
    const r = await fetch(API, { cache: "no-store" });
    if (!r.ok) throw new Error(r.status);
    const s = await r.json();
    for (const b of Object.keys(SH)) SH[b] = s[b] || {};
    store.online = true;
    store.lastPull = Date.now();
    try { localStorage.setItem(CACHE_KEY, JSON.stringify(SH)); } catch (e) {}
    return true;
  } catch (e) { store.online = false; return false; }
}

async function push(op, bucket, key, value) {
  if (op === "set") SH[bucket][key] = typeof value === "string" ? value : JSON.stringify(value);
  else delete SH[bucket][key];
  try { localStorage.setItem(CACHE_KEY, JSON.stringify(SH)); } catch (e) {}
  try {
    const r = await fetch(API, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ op, bucket, key, value }) });
    if (!r.ok) throw new Error(r.status);
    store.online = true;
  } catch (e) {
    store.online = false;
    toast("저장이 서버에 안 됐어요. 이 브라우저에는 남아 있어요");
  }
  showSync();
}

